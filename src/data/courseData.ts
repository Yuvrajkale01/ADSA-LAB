export function getAllTopics() {
  return courseUnits.flatMap(u => u.topics);
}

export function getTopicById(id: string) {
  return getAllTopics().find(t => t.id === id);
}

export function getUnitById(id: string) {
  return courseUnits.find(u => u.id === id);
}

export function getTopicsByUnit(unitId: string) {
  const unit = getUnitById(unitId);
  return unit ? unit.topics : [];
}

export function getAllTopicIds() {
  return getAllTopics().map(t => t.id);
}

